    //create schedule
    public void createSchedule(){
        try{
            if(cmbSongLeader.getSelectedIndex() == -1 || dateChooser == null){
                JOptionPane.showMessageDialog(this, "Please select Song Leader and Date");
                return;
            }

            String selectedItem = cmbSongLeader.getSelectedItem().toString();
            String[] parts = selectedItem.split(" ", 2);
            int songLeaderId = Integer.parseInt(parts[0]);
            String songLeaderName = parts[1];

            java.sql.Date sqlDate = new java.sql.Date(dateChooser.getDate().getTime());

            Connection conn = DatabaseConnection.conn();
            
            String checkQuery = "SELECT COUNT(*) FROM schedule WHERE schedule_date = ?";
            PreparedStatement checkStmt = conn.prepareStatement(checkQuery);
            checkStmt.setDate(1, sqlDate);
            ResultSet checkRs = checkStmt.executeQuery();

            if (checkRs.next() && checkRs.getInt(1) > 0) {
                JOptionPane.showMessageDialog(this, "A schedule already exists for the selected date.");
                conn.close();
                return;
            }

            String insertSql = "INSERT INTO schedule (song_leader_id, song_leader_name, schedule_date) VALUES (?, ?, ?)";
            PreparedStatement stmt = conn.prepareStatement(insertSql);
            stmt.setInt(1, songLeaderId);
            stmt.setString(2, songLeaderName);
            stmt.setDate(3, sqlDate);

            int rows = stmt.executeUpdate();

             if (rows > 0) {
              JOptionPane.showMessageDialog(this, "Schedule saved successfully!");
             } else {
                 JOptionPane.showMessageDialog(this, "Schedule not saved.");
             }
             
             loadSchedule();
           
       }catch(Exception e){
             JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
       }
    }
