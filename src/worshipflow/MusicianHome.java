    public void viewLyrics(JTable table){
        int selectedRow = table.getSelectedRow();
         
         if(selectedRow == -1){     
             JOptionPane.showMessageDialog(null, "Please select a song first");
             return;
         }
         
        
         String title = table.getValueAt(selectedRow, 0).toString().trim();
         
         String lyrics = null;
         try {
            Connection conn = DatabaseConnection.conn();
            String sql = "SELECT lyrics FROM song WHERE title = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1,title);
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {
                lyrics = rs.getString("lyrics");
            }
            conn.close();
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error fetching lyrics: " + ex.getMessage());
            return;
        }

        if (lyrics == null || lyrics.trim().isEmpty()) {   
            JOptionPane.showMessageDialog(this, "Lyrics not found.");
            return;
        }

        // Show the dialog
        LyricsPopUpWindow dialog = new LyricsPopUpWindow(this, true);
        dialog.setLyricsData(title, lyrics);
        dialog.setVisible(true);

     }
    
    public void viewChords(JTable table){
        int selectedRow = table.getSelectedRow();
         
         if(selectedRow == -1){     
             JOptionPane.showMessageDialog(null, "Please select a song first");
             return;
         }
         
        
         String title = table.getValueAt(selectedRow, 0).toString().trim();
         
         String chords = null;
         try {
            Connection conn = DatabaseConnection.conn();
            String sql = "SELECT chords FROM song WHERE title = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1,title);
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {
                chords = rs.getString("chords");
            }
            conn.close();
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error fetching chords: " + ex.getMessage());
            return;
        }

        if (chords == null || chords.trim().isEmpty()) {   
            int result = JOptionPane.showConfirmDialog(
                    this, 
                    "No chords found for \"" + title +  "\".\nWould you like to add?",
                    "Chords NOT found!",
                    JOptionPane.YES_NO_OPTION
                    );
            if(result == JOptionPane.YES_OPTION){
                addChords dialog = new addChords(this, true);
                dialog.setSongTitle(title);
                dialog.setVisible(true);
            }
            return;
        }

        // Show the dialog
        ChordsPopUpWindow dialog = new ChordsPopUpWindow(this, true);
        dialog.setLyricsData(title, chords);
        dialog.setVisible(true);

     }
  
