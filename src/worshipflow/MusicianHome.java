    private void txtSearchsongKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSearchsongKeyReleased
        String keyword = txtSearchsong.getText().trim();
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(new String[]{"Song ID", "Title", "Artist", "Song Key"});
        tblSongs.setModel(model);

        try{
            Connection conn = DatabaseConnection.conn();
            String sql = "SELECT id, title, artist, song_key FROM song WHERE title LIKE ? OR artist LIKE ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1, "%" + keyword + "%");
            stmt.setString(2, "%" + keyword + "%");
            ResultSet rs = stmt.executeQuery();

            while(rs.next()){
                model.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("title"),
                    rs.getString("artist"),
                    rs.getString("song_key"),
                });

            }

            conn.close();
        }catch(Exception e){
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_txtSearchsongKeyReleased

