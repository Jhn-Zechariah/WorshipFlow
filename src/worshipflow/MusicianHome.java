    private void addProgressionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addProgressionActionPerformed
        int selectedRow = tblSetlist.getSelectedRow();
        
        if(selectedRow == -1){
             JOptionPane.showMessageDialog(this, "Please select a song");
             return;
        }
        
        String songTitle = tblSetlist.getValueAt(selectedRow, 0).toString();
        
        try{
             Connection conn = DatabaseConnection.conn();
             String sql = "SELECT id, chords FROM song WHERE title = ?";
             PreparedStatement stmt = conn.prepareStatement(sql);
             stmt.setString(1, songTitle);
             ResultSet rs = stmt.executeQuery();
             
             if(rs.next()){
                 String chords = rs.getString("chords");
                 
                 if(chords != null && !chords.isEmpty()){
                     JOptionPane.showMessageDialog(this, "This song already has chord progression");
                     return;
                 }
                 
                 addChords dialog = new addChords(this, true);
                 dialog.setSongTitle(songTitle);
                 dialog.setVisible(true);
             }
        }catch(Exception e){
            e.printStackTrace();
             JOptionPane.showMessageDialog(this, "Error:" + e.getMessage()); 
        }
    }//GEN-LAST:event_addProgressionActionPerformed

