    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String title = songTitle.getText().trim();
        String artist = songArtist.getText().trim();
        String lyrics = songLyrics.getText().trim();
        String key = songKey.getText().trim();

        if (title.isEmpty() || artist.isEmpty() || lyrics.isEmpty() || key.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }

        try {
            Connection conn = DatabaseConnection.conn();

            String insert = "INSERT INTO song (title, artist, lyrics, song_key) VALUES (?, ?, ?, ?)";
            PreparedStatement stmt = conn.prepareStatement(insert);
            stmt.setString(1, title);
            stmt.setString(2, artist);
            stmt.setString(3, lyrics);
            stmt.setString(4, key);
            stmt.executeUpdate();

            conn.close();
            
            
            JOptionPane.showMessageDialog(this, "Song added!");
            this.dispose();

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Failed to save song: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

  
