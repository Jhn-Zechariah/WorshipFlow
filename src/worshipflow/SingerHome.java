    public void viewLyrics(JTable table){
        int selectedRow = table.getSelectedRow();
         
         if(selectedRow == -1){     
             JOptionPane.showMessageDialog(null, "Please select a song first");
             return;
         }
         
        
         String title = table.getValueAt(selectedRow, 0).toString().trim();
         
         String lyrics = null;
         try {
            Connection conn = DatabaseConnection.conn();
            String sql = "SELECT lyrics FROM song WHERE title = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1,title);
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {
                lyrics = rs.getString("lyrics");
            }
            conn.close();
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error fetching lyrics: " + ex.getMessage());
            return;
        }

        if (lyrics == null | lyrics.trim().isEmpty()) {   
            JOptionPane.showMessageDialog(this, "Lyrics not found.");
            return;
        }

        // Show the dialog
        LyricsPopUpWindow dialog = new LyricsPopUpWindow(this, true);
        dialog.setLyricsData(title, lyrics);
        dialog.setVisible(true);

     }
     
    public void saveSetlist(){
         try{
             Connection conn = DatabaseConnection.conn();
             conn.setAutoCommit(false);
             
            int scheduleID = getScheduleId();
             
             
             //insert statement
             String insertSql = "INSERT INTO setlist (schedule_id, song_id, position) VALUES (?,?,?)";
             PreparedStatement insertStmt = conn.prepareStatement(insertSql);
             
             DefaultTableModel model = (DefaultTableModel) tableSetList.getModel();
             int rowCount = model.getRowCount();
             
             if(rowCount == 0){
                 JOptionPane.showMessageDialog(this, "Setlist is empty");
                 return;
             }
             
             for(int i = 0; i < rowCount; i++){
                 String songTitle = model.getValueAt(i, 0).toString();
                 
                 String songQuery = "SELECT id FROM song WHERE title = ?";
                 PreparedStatement songStmt = conn.prepareStatement(songQuery);
                 songStmt.setString(1, songTitle);
                 ResultSet songRs = songStmt.executeQuery();
                 
                 if(songRs.next()){
                     int songId = songRs.getInt("id");
                     
                     insertStmt.setInt(1, scheduleID);
                     insertStmt.setInt(2, songId);
                     insertStmt.setInt(3, i + 1);
                     insertStmt.addBatch();
                 }else{
                     JOptionPane.showMessageDialog(this, "Song not found in the Database");
                     return;
                 }
                 
                 
             }
             
            insertStmt.executeBatch();
            conn.commit();
            conn.close();

            JOptionPane.showMessageDialog(this, "Setlist saved succesfully");

             
         }catch(Exception e){
             e.printStackTrace();
             JOptionPane.showMessageDialog(this, "Error savong setlist");
         }
     }
     
