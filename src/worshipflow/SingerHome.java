    public void loadSetlistBySchedule(int scheduleId){
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(new String[]{"Song Title", "Artist", "Song Key", "Position"});
        tblSetlist.setModel(model);
        try{
            Connection conn = DatabaseConnection.conn();
            
            String query = "SELECT s.title, s.artist, s.song_key, sl.position " +
                    "FROM setlist sl " +
                    "JOIN  song s ON sl.song_id = s.id " +
                    "WHERE sl.schedule_id = ? " +
                    "ORDER BY sl.position";
            PreparedStatement stmt = conn.prepareStatement(query);
            stmt.setInt(1, scheduleId);
            ResultSet rs = stmt.executeQuery();
            
            while(rs.next()){
                model.addRow(new Object[]{
                    rs.getString("title"),
                    rs.getString("artist"),
                    rs.getString("song_key"),
                    rs.getInt("position")
                });
          
            }
            
            conn.close();
                           
        }catch(Exception e){
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error laoding setlist: " + e.getMessage());
        }
    
    }
    
    public void loadAssignedSongLeader(int scheduleId){
        try{
            Connection conn = DatabaseConnection.conn();
            String query = "SELECT u.username "+
                    "FROM schedule s "+
                    "JOIN users u ON s.song_leader_id = u.id "+
                    "WHERE s.id = ?";
            PreparedStatement stmt = conn.prepareStatement(query);
            stmt.setInt(1, scheduleId);
            ResultSet rs = stmt.executeQuery();
            
            if(rs.next()){
                lblSongleader.setText(rs.getString("username"));
            }else{
                lblSongleader.setText("User not found");
            }
        }catch(Exception e){
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
        }
    }   
    
   
   
