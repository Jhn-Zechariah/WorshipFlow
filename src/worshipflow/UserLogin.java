    //login button
    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String emails = email.getText();
        String roles = role.getSelectedItem().toString();
        String pass = new String(password.getPassword());
        
        
        if(emails.isEmpty() || pass.isEmpty()){
            JOptionPane.showMessageDialog(this, "All fields are requied to be filled");
            return;
        }
        
        try{
            Connection conn = DatabaseConnection.conn();
            String sql = "SELECT * FROM users WHERE email = ? AND password = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1, emails);
            stmt.setString(2, pass);
            
            ResultSet rs = stmt.executeQuery();
            
            if(rs.next()){
                TableUser users = new TableUser(
                       rs.getInt("Id"),
                       rs.getString("username"),
                       rs.getString("email"),
                       rs.getString("role"),
                       rs.getString("password")
                       
               );
                String dbRole = rs.getString("role");
                
                //checks where page will land
                if(dbRole.equalsIgnoreCase(roles)){
                    JOptionPane.showMessageDialog(this, "Login Successful");
                    
                    switch (dbRole){
                        case "Admin":
                            new AdminPage().setVisible(true);
                        break;
                        case "Song Leader":
                            new SingerHome().setVisible(true);
                        break;
                        case "Musician":
                            new MusicianHome().setVisible(true);
                        break;
                        default:
                            JOptionPane.showMessageDialog(this, "Unrecognized Role: " + dbRole);
                    }
                    this.dispose();
                }else{
                    JOptionPane.showMessageDialog(this, "Incorrect Role");
                }
            }else{
                JOptionPane.showMessageDialog(this, "Invalid email or password");
            
            }
            
            rs.close();
            stmt.close();
            conn.close();
            
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error" + e.getMessage());
        }
        
        email.setText("");
        password.setText("");
    }//GEN-LAST:event_btnLoginActionPerformed

