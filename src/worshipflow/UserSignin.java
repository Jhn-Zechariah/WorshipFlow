    //sign in button
    private void loginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginButtonActionPerformed
        String user = username.getText();
        String emails = email.getText();
        String roles = role.getSelectedItem().toString();
        String pass = new String(password.getPassword());
        
        //checks is fields are not empty
        if(user.isEmpty() || emails.isEmpty()|| roles.isEmpty()|| pass.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please fill out all fields");
            return;
        }
        
        try{
            Connection conn = DatabaseConnection.conn();
            String sql = "INSERT INTO users (username, email, role, password) VALUES(?,?,?,?)";
            PreparedStatement stmt = conn.prepareStatement(sql);
            
            stmt.setString(1, user);
            stmt.setString(2, emails);
            stmt.setString(3, roles);
            stmt.setString(4, pass);
            
            int rowInserted = stmt.executeUpdate();
            if(rowInserted > 0){
                JOptionPane.showMessageDialog(this, "Account Successfuly Created!");
            }else{
                JOptionPane.showMessageDialog(this, "Sign up Failed!");
            }
            
            stmt.close();
            conn.close();
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
        
        username.setText("");
        email.setText("");
        password.setText("");
    }//GEN-LAST:event_loginButtonActionPerformed
    
