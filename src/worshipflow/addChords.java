    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        String chords = chordSpace.getText().trim();
        String title = lblTitle.getText();
        
        if(chords.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please write the chord progression");
            return;
        }
        
        try{
           Connection conn = DatabaseConnection.conn();
           
           String query = "UPDATE song SET chords = ? WHERE title = ?";
           PreparedStatement stmt = conn.prepareStatement(query);
           stmt.setString(1, chords);
           stmt.setString(2, title);
           
           int row = stmt.executeUpdate();
           conn.close();
           
           if(row > 0){
                JOptionPane.showMessageDialog(this, "Chords saved successfuly");
                this.dispose();
           }else{
               JOptionPane.showMessageDialog(this, "Failed to save chords");
           }
           
        }catch(Exception e){
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_saveActionPerformed

